const enc = new TextEncoder();
// The loaded name has a part the scan cannot know (p + ".js"), so only reading every file reaches docs/evil.js.
const A = "p + '.js'";
const reaches = (body: string) => {
  const o = { "package.json": JSON.stringify({ name: "x", version: "1.0.0", scripts: { postinstall: "node hook.js" } }), "hook.js": `${body}\n`, "docs/evil.js": "1;\n", "README.md": "x\n", "lib/a.js": "1;\n" };
  return installView(new Map(Object.entries(o).map(([k, v]) => [k, enc.encode(v)]))).files.includes("docs/evil.js");
};

